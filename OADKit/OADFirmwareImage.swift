import Foundation

// Firmware image helper for the TI BLE OAD firmware update process.
//
// Constructed from a full-flash Intel HEX string (e.g. from String(contentsOf: url)),
// where the URL points to a fullflash hex image produced by hexmerge.py.
//
// Parses the Intel HEX records to find the image start address and builds a single
// data blob from all bytes in all records.
//
// Use nextBlock() to obtain the next 16-byte block during programming.
//
// Notes: Currently only supports image type 1 (app+stack) and was only tested for
// off-chip OAD using the "safe" method, where the first and last flash pages remain
// intact. Tested with fullflash Intel HEX files generated by hexmerge.py from the
// intelhex Python module, as described in TI's OAD user guide.
//
// Inspired by OAD code in the TI Android SensorTag app.

final class FirmwareImage {

    // MARK: - Image header

    private(set) var crc0: Int = 0
    private(set) var crc1: Int = 0
    var ver: Int = 0
    private(set) var len: Int = 0
    private(set) var addr: UInt32 = 0
    let uid = [UInt8](repeating: 0x45, count: 4)
    var imgType: ImgType = .EFL_OAD_IMG_TYPE_APP

    // Image binary blob
    private(set) var data = Data()

    // Fixed sizes for Intel HEX from hexmerge.py / TI OAD
    private let oadBlockSize = 16
    private let halFlashWordSize = 4

    // Programming counters used during bulk block transfer
    private(set) var iBlocks = 0 // Number of blocks programmed
    private(set) var nBlocks = 0 // Total number of blocks

    // https://en.wikipedia.org/wiki/Intel_HEX
    private enum RecordType: Int {
        case data = 0x00
        case eof
        case extSegAddr
        case startSegAddr
        case extLinAddr
        case startLinAddr
    }

    // Image types for TI OAD target
    enum ImgType: Int {
        case EFL_OAD_IMG_TYPE_APP = 1 // TODO: support other types
    }

    // MARK: - Init

    /// Initialize with a hex file string read from disk.
    init(hexString: String) {
        let lines = Self.generateLines(from: hexString)
        parseLines(lines)

        // Update header fields (start address was set during parse)
        len = data.count / (oadBlockSize / halFlashWordSize)
        crc1 = 0xFFFF
        crc0 = calcImageCRC(startPage: 0, data: data)

        resetProgress()
    }

    convenience init?(url: URL) {
        guard let hexData = try? Data(contentsOf: url),
              let hex = String(data: hexData, encoding: .utf8) else {
            return nil
        }
        self.init(hexString: hex)
    }

    // MARK: - Block transfer

    /// Reset block transfer counters.
    func resetProgress() {
        iBlocks = 0
        nBlocks = len / (oadBlockSize / halFlashWordSize)
    }

    /// Request the next block in the image blob.
    func nextBlock() -> Data? {
        let b = block(blockNum: iBlocks)
        iBlocks += 1
        return b
    }

    /// Request a specific block.
    private func block(blockNum: Int) -> Data? {
        guard blockNum < nBlocks else { return nil }

        iBlocks = blockNum

        var block = [UInt8](repeating: 0, count: oadBlockSize + 2)
        block[0] = UInt8(blockNum & 0xFF)
        block[1] = UInt8((blockNum >> 8) & 0xFF)

        let range = blockNum * oadBlockSize ..< (blockNum + 1) * oadBlockSize
        data.subdata(in: range).copyBytes(to: &block[2], count: oadBlockSize)

        return Data(block)
    }

    // MARK: - HEX parsing

    private static func generateLines(from string: String) -> [String] {
        string.components(separatedBy: .newlines).filter { !$0.isEmpty }
    }

    // FIXME: Parsing is still relatively slow for large images.
    private func parseLines(_ lines: [String]) {
        var currentAddressBase: UInt32 = 0
        var currentAddress: UInt32?

        for line in lines {
            guard line.first == ":" else { continue }

            guard let numBytes = Self.hexInt(line, start: 1, length: 2),
                  let recordTypeInt = Self.hexInt(line, start: 7, length: 2),
                  let recordType = RecordType(rawValue: recordTypeInt) else {
                continue
            }

            switch recordType {
            case .data:
                guard var blockAddr = Self.hexUInt32(line, start: 3, length: 4) else { continue }

                // Block address is relative to a previous base address record (if any)
                blockAddr += currentAddressBase

                // First data block address becomes the image header start address.
                // The OAD target programs the image starting at this address after reboot.
                if currentAddress == nil {
                    addr = blockAddr / UInt32(oadBlockSize / halFlashWordSize)
                }

                // Pad gaps between non-contiguous addresses with 0xFF
                if let previous = currentAddress, previous < blockAddr {
                    let numPadBytes = Int(blockAddr - previous)
                    data.append(contentsOf: [UInt8](repeating: 0xFF, count: numPadBytes))
                }

                currentAddress = blockAddr

                guard let lineData = Self.hexBytes(line, start: 9, byteCount: numBytes) else { continue }

                data.append(lineData)
                var nextAddress = blockAddr + UInt32(lineData.count)

                // We only support 16-byte blocks; pad shorter records with 0xFF
                if lineData.count < oadBlockSize {
                    let numBytesToPad = oadBlockSize - lineData.count
                    data.append(contentsOf: [UInt8](repeating: 0xFF, count: numBytesToPad))
                    nextAddress += UInt32(numBytesToPad)
                }

                currentAddress = nextAddress

            case .extLinAddr:
                guard var extLinAddr = Self.hexUInt32(line, start: 9, length: 4) else { continue }
                extLinAddr <<= 16
                // Subsequent addresses are relative to this base
                currentAddressBase = extLinAddr

            case .eof:
                break

            // Remaining record types are not produced by hexmerge.py for TI BLE OAD
            case .extSegAddr, .startSegAddr, .startLinAddr:
                break
            }
        }
    }

    /// Extract an integer from a hex substring of `line`.
    private static func hexInt(_ line: String, start: Int, length: Int) -> Int? {
        guard let value = hexUInt32(line, start: start, length: length) else { return nil }
        return Int(value)
    }

    private static func hexUInt32(_ line: String, start: Int, length: Int) -> UInt32? {
        guard line.count >= start + length else { return nil }
        let from = line.index(line.startIndex, offsetBy: start)
        let to = line.index(from, offsetBy: length)
        return UInt32(line[from..<to], radix: 16)
    }

    private static func hexBytes(_ line: String, start: Int, byteCount: Int) -> Data? {
        let length = byteCount * 2
        guard line.count >= start + length else { return nil }
        let from = line.index(line.startIndex, offsetBy: start)
        let to = line.index(from, offsetBy: length)
        return String(line[from..<to]).dataFromHexString()
    }

    // MARK: - Header / CRC

    /// Print image header for debugging.
    func printHdr() {
        print("OADKit ImgHdr.len =", len)
        print("OADKit ImgHdr.ver =", ver)
        print("OADKit ImgHdr.uid =", String(format: "0x%02x%02x%02x%02x", uid[0], uid[1], uid[2], uid[3]))
        print("OADKit ImgHdr.addr =", String(format: "0x%04x", UInt16(addr & 0xFFFF)))
        print("OADKit ImgHdr.imgType =", imgType)
        print("OADKit ImgHdr.crc0 =", String(format: "0x%04x", UInt16(crc0 & 0xFFFF)))
        print("OADKit identify =", imgIdentifyRequestData().hexArrayString())
    }

    /// Calculate CRC over the binary blob.
    private func calcImageCRC(startPage: Int, data: Data) -> Int {
        var crc = 0
        var pageByteAddr = startPage * 0x1000

        var page = startPage
        var pageEnd = len / (0x1000 / 4)
        let osetEnd = (len - (pageEnd * (0x1000 / 4))) * 4

        pageEnd += startPage

        while true {
            var oset = 0
            while oset < 0x1000 {
                if page == startPage && oset == 0x00 {
                    // Skip the CRC and shadow.
                    // Increments by 3 because oset is incremented by 1 each pass.
                    oset += 3
                } else if page == pageEnd && oset == osetEnd {
                    crc = crc16(startCrc: crc, startVal: 0x00)
                    crc = crc16(startCrc: crc, startVal: 0x00)
                    return crc
                } else {
                    data.withUnsafeBytes { rawBuffer in
                        let bytes = rawBuffer.bindMemory(to: UInt8.self)
                        crc = crc16(startCrc: crc, startVal: Int(bytes[pageByteAddr + oset]))
                    }
                }
                oset += 1
            }

            page += 1
            pageByteAddr = page * 0x1000
        }
    }

    private func crc16(startCrc: Int, startVal: Int) -> Int {
        var val = startVal
        var crc = startCrc
        let poly = 0x1021

        for _ in 0..<8 {
            let msb = (crc & 0x8000) == 0x8000
            crc <<= 1
            if (val & 0x80) == 0x80 {
                crc |= 0x0001
            }
            if msb {
                crc ^= poly
            }
            val <<= 1
        }

        return crc
    }

    /// Generate image header data used to identify with the OAD target.
    func imgIdentifyRequestData() -> Data {
        var tmp = [UInt8]()
        tmp.reserveCapacity(16)

        tmp.append(UInt8(crc0 & 0xFF))
        tmp.append(UInt8((crc0 >> 8) & 0xFF))
        tmp.append(UInt8(crc1 & 0xFF))
        tmp.append(UInt8((crc1 >> 8) & 0xFF))
        tmp.append(UInt8(ver & 0xFF))
        tmp.append(UInt8((ver >> 8) & 0xFF))
        tmp.append(UInt8(len & 0xFF))
        tmp.append(UInt8((len >> 8) & 0xFF))
        tmp.append(contentsOf: uid)
        tmp.append(UInt8(addr & 0xFF))
        tmp.append(UInt8((addr >> 8) & 0xFF))
        tmp.append(UInt8(imgType.rawValue & 0xFF))
        tmp.append(0xFF)

        return Data(tmp)
    }
}

// MARK: - Helpers

extension Data {
    func hexArrayString() -> String {
        let parts = map { String(format: "0x%02x", $0) }
        return "[\(parts.joined(separator: ", "))]"
    }
}

extension String {
    /// Convert a hex string (optional spaces / angle brackets) into `Data`.
    func dataFromHexString() -> Data? {
        let trimmed = trimmingCharacters(in: CharacterSet(charactersIn: "<> "))
            .replacingOccurrences(of: " ", with: "")
        guard !trimmed.isEmpty, trimmed.count % 2 == 0 else { return nil }

        var data = Data()
        data.reserveCapacity(trimmed.count / 2)

        var index = trimmed.startIndex
        while index < trimmed.endIndex {
            let next = trimmed.index(index, offsetBy: 2)
            guard let byte = UInt8(trimmed[index..<next], radix: 16) else { return nil }
            data.append(byte)
            index = next
        }

        return data
    }
}
